# ── Helpers ──────────────────────────────────────────────────────────────────

def _now() -> datetime:
    return datetime.now(UTC)


def _parse_ma_id(ma_id: str) -> str | None:
    """Extract MA-####### from a string, return None if invalid."""
    if not ma_id:
        return None
    s = str(ma_id).strip()
    if s.startswith("MA-") and s[3:].isdigit():
        return s
    return None


def _safe_str(val: Any) -> str | None:
    """Convert value to string, return None for empty/NaN."""
    if val is None:
        return None
    s = str(val).strip()
    if not s or s.lower() in ("none", "nan", "null", "n/a", ""):
        return None
    return s


# ── Source File Registration ─────────────────────────────────────────────────


async def register_muhide_source_file(
    session: AsyncSession,
    tenant_id: str,
    filename: str,
    file_path: str,
    row_count: int,
    source_system: str = "muhide_v2",
    uploaded_by: str = "system",
) -> str:
    """Register a MUHIDE source file in md_source_files.

    Returns the file ID.
    """
    import hashlib

    # Compute hash if file exists
    file_hash = "unknown"
    file_size = 0
    mime_type = "text/csv"
    try:
        p = Path(file_path)
        if p.exists():
            content = p.read_bytes()
            file_hash = hashlib.sha256(content).hexdigest()
            file_size = len(content)
            if file_path.endswith(".parquet"):
                mime_type = "application/octet-stream"
            elif file_path.endswith(".xlsx"):
                mime_type = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
    except Exception:
        pass

    file_id = str(uuid.uuid4())
    now = _now()

    await session.execute(
        text(
            "INSERT INTO md_source_files "
            "(id, tenant_id, filename, storage_path, file_hash_sha256, file_size_bytes, "
            "mime_type, sheet_count, total_rows, source_system, uploaded_by, uploaded_at, status) "
            "VALUES (:id, :tenant_id, :filename, :path, :hash, :size, "
            ":mime, 1, :rows, :source, :by, :now, 'completed') "
            "ON CONFLICT DO NOTHING"
        ),
        {
            "id": file_id,
            "tenant_id": tenant_id,
            "filename": filename,
            "path": file_path,
            "hash": file_hash,
            "size": file_size,
            "mime": mime_type,
            "rows": row_count,
            "source": source_system,
            "by": uploaded_by,
            "now": now,
        },
    )

    return file_id


# ── Bulk Source Row Ingestion ────────────────────────────────────────────────


async def bulk_insert_source_rows(
    session: AsyncSession,
    tenant_id: str,
    source_file_id: str,
    source_id: str,
    rows: list[dict[str, Any]],
    entity_type: str = "company",
) -> int:
    """Bulk insert source rows with batch processing.

    Each row dict must have at minimum:
    - source_record_id: str
    - raw_payload: dict

    Returns count of rows inserted.
    """
    now = _now()
    inserted = 0

    # Process in batches
    for i in range(0, len(rows), BATCH_SIZE):
        batch = rows[i:i + BATCH_SIZE]
        batch_params = []

        for idx, row in enumerate(batch):
            row_id = str(uuid.uuid4())
            source_record_id = str(row.get("source_record_id", f"ROW-{i + idx}"))
            raw_payload = row.get("raw_payload", row)

            batch_params.append({
                "id": row_id,
                "tenant_id": tenant_id,
                "file_id": source_file_id,
                "source_id": source_id,
                "source_record_id": source_record_id,
                "row_number": i + idx,
                "payload": json.dumps(raw_payload, ensure_ascii=False, default=str),
                "entity_type": entity_type,
                "now": now,
            })

        if batch_params:
            result = await session.execute(
                text(
                    "INSERT INTO md_source_rows "
                    "(id, tenant_id, source_file_id, source_id, source_record_id, row_number, "
                    "raw_payload, entity_type, resolution_status, created_at) "
                    "VALUES (:id, :tenant_id, :file_id, :source_id, "
                    ":source_record_id, :row_number, "
                    "CAST(:payload AS JSONB), :entity_type, 'pending', :now) "
                    "ON CONFLICT (source_id, source_record_id) DO NOTHING"
                ),
                batch_params,
            )
            batch_inserted = getattr(result, "rowcount", None)
            if not isinstance(batch_inserted, int) or batch_inserted < 0:
                raise RuntimeError(
                    "Database driver did not report the number of inserted source rows"
                )
            inserted += batch_inserted

    return inserted


