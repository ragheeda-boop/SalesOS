"""MUHIDE v2 Ingestion Adapter — Bulk Import to Master Data.

Handles the MUHIDE v2 dataset import into the SalesOS Master Data platform.
Designed for bulk operations with batch inserts, chunked processing, and
idempotent re-import support.

Key design decisions:
- MA-####### IDs are preserved as legacy aliases, never as Global IDs
- Global IDs are generated by ID Registry (G-C-XXXXXXXX)
- Source rows are immutable after insert
- Duplicate source keys are handled with ON CONFLICT DO NOTHING
- Batch inserts use executemany for performance
- Progress tracking enables resumable execution
"""

